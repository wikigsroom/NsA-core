"""Build the bootstrap and collect explicitly selected compiled slots into one APK."""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--slots', type=Path, required=True, help='Local JSON {slots:[{library_path, registry:{...}}]}')
    parser.add_argument('--ndk', type=Path, default=ROOT / 'tools/player/toolchains/android-ndk-r27c')
    args = parser.parse_args()
    entries = json.loads(args.slots.read_text(encoding='utf-8'))['slots']
    primary_names = {entry['registry']['library_name'] for entry in entries}
    target = ROOT / 'android/app/src/main/jniLibs/arm64-v8a'; target.mkdir(parents=True, exist_ok=True)
    clang = args.ndk / 'toolchains/llvm/prebuilt/windows-x86_64/bin/clang.exe'
    subprocess.run([str(clang), '--target=aarch64-linux-android31', '-O2', '-shared', '-fPIC', '-Wall', '-Werror=return-type',
                    str(ROOT / 'android/app/src/main/cpp/bootstrap.c'), '-o', str(target / 'libnsa_bootstrap.so'), '-landroid', '-llog', '-ldl', '-Wl,-z,max-page-size=16384'], check=True)
    registry = {'registry_schema': 1, 'app_version_code': 1, 'bootstrap_api_version': 1, 'slots': []}
    seen = set()
    expected_libraries = {'libnsa_bootstrap.so'}
    for entry in entries:
        item = entry['registry']
        if not re.fullmatch(r'libnsa_[a-z0-9_]+\.so', item['library_name']) or item['library_name'] in expected_libraries:
            raise ValueError('Invalid or duplicate primary runtime library')
        expected_libraries.add(item['library_name'])
        if item['runtime_slot_id'] in seen: raise ValueError('Duplicate runtime slot')
        seen.add(item['runtime_slot_id'])
        source = Path(entry['library_path'])
        shutil.copy2(source, target / item['library_name'])
        with source.open('rb') as incoming: item['library_sha256'] = hashlib.file_digest(incoming, 'sha256').hexdigest()
        registry['slots'].append(item)
        for dependency in entry.get('dependencies', []):
            library = Path(dependency)
            if not re.fullmatch(r'lib[A-Za-z0-9_.+-]+\.so', library.name) or library.name == 'libnsa_bootstrap.so' or library.name in primary_names:
                raise ValueError('Invalid runtime dependency name')
            if library.name in expected_libraries:
                with library.open('rb') as incoming: source_sha = hashlib.file_digest(incoming, 'sha256').digest()
                with (target / library.name).open('rb') as incoming: retained_sha = hashlib.file_digest(incoming, 'sha256').digest()
                if source_sha != retained_sha: raise ValueError('Two slots require different bytes under one dependency name')
            expected_libraries.add(library.name)
            shutil.copy2(library, target / library.name)
    # This directory is generated by this tool. A demo build must not retain an
    # unselected private runtime from an earlier two-game development build.
    for previous in target.glob('*.so'):
        if previous.name not in expected_libraries: previous.unlink()
    assets = ROOT / 'android/app/src/main/assets'; assets.mkdir(parents=True, exist_ok=True)
    (assets / 'runtime-registry.json').write_text(json.dumps(registry, separators=(',', ':')), encoding='utf-8')
    print('Bootstrap and', len(seen), 'compiled slots prepared. No game content was embedded.')

if __name__ == '__main__': main()
